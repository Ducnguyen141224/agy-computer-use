import assert from 'node:assert/strict';
import {spawn,execFileSync} from 'node:child_process';
import {createInterface} from 'node:readline';
import {once} from 'node:events';
import {randomUUID} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {NativeBridge} from '../src/native-bridge.mjs';
import {DesktopController} from '../src/desktop-controller.mjs';
import {browserFixture} from '../tests/browser-fixture.mjs';

process.env.AGY_DESKTOP_TEST_SCOPE=randomUUID().replaceAll('-','');
const root=fileURLToPath(new URL('../',import.meta.url));
execFileSync('dotnet',['build','tests/fixture/DesktopFixture.csproj','-c','Release','--nologo'],{cwd:root,stdio:'pipe',windowsHide:true});
const exe=fileURLToPath(new URL('../tests/fixture/bin/Release/net10.0-windows/DesktopFixture.exe',import.meta.url));
const title=`AGY activity ${randomUUID()}`,fixture=spawn(exe,[title],{stdio:'ignore'});
const probe=spawn(exe,['--control-probe',String(fixture.pid)],{stdio:['pipe','pipe','ignore'],windowsHide:true});
const lines=createInterface({input:probe.stdout});
const inspect=async command=>{const next=once(lines,'line');probe.stdin.write(command+'\n');const [line]=await next;const data=JSON.parse(line);assert.ok(!data.error,line);return data;};
const bridge=new NativeBridge(),desktop=new DesktopController(bridge),web=await browserFixture();
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));let checks=0;
const check=(value,label)=>{assert.ok(value,label);checks++;process.stdout.write(`PASS ${label}\n`);};
const call=async(name,args)=>{const result=await desktop.request(name,args);assert.ok(result.ok,JSON.stringify(result));return result.data;};
const visual=()=>inspect(`visual:${bridge.child.pid}`);
const hidden=async()=>{await pause(350);const v=await visual();assert.ok(!v.rendered&&!v.pointer_visible,JSON.stringify(v));};
const shown=async()=>{for(let i=0;i<50;i++){const v=await visual();if(v.rendered&&v.pointer_visible)return v;await pause(20);}assert.fail('Owned helper overlays did not become visible during input.');};
try {
  const ready=await call('desktop_query',{operation:'window_wait',query:title,timeout_ms:5000});
  const owned=ready.windows.find(w=>w.pid===fixture.pid);assert.ok(owned,JSON.stringify({ready,fixture_pid:fixture.pid,exit:fixture.exitCode}));const window_id=owned.id;
  await hidden();check(true,'independent Win32 observer sees no frame/pointer during desktop reads');
  await call('desktop_system',{operation:'cursor_config',agent:'idle-check',cursor:{enabled:true}});
  check(!(await call('desktop_system',{operation:'cursor_status'})).renderer.rendered,'configuring a custom cursor does not display it while idle');
  await call('desktop_system',{operation:'cursor_remove',agent:'idle-check'});
  const found=await call('desktop_find',{window_id,name:'Message',role:'edit'});const ref=found.items[0].ref;
  await call('desktop_act',{action:'focus_window',window_id});await call('desktop_act',{action:'focus',ref});await hidden();
  const wait=call('desktop_run',{code:'desktop.query({operation:"time_wait",timeout_ms:800});return true;'});
  await pause(200);await hidden();await wait;check(true,'native workflow waits keep Escape armed while overlays remain hidden');
  const pad=(await call('desktop_find',{window_id,name:'Gesture pad'})).items[0];
  const destination=(await call('desktop_find',{window_id,name:'Drop zone'})).items[0];
  const dragging=call('desktop_act',{action:'drag',ref:pad.ref,to_ref:destination.ref,duration_ms:1300,drop_delay_ms:300});
  const v=await shown();check(v.click_through&&v.no_activate&&v.foreground===fixture.pid,'real native drag displays owned frame/pointer without stealing focus');
  await dragging;await hidden();check(true,'frame and pointer both hide after actual native input ends');
  await call('browser_session',{operation:'start',connection:'isolated',browser:'chrome',headless:false});
  const tab=await call('browser_tabs',{operation:'new',url:web.url+'/main?tab=Activity'});await hidden();
  await call('browser_read',{tab_id:tab.tab_id,operation:'snapshot'});await hidden();check(true,'browser DOM reads do not display overlays');
  const input=desktop.request('browser_act',{tab_id:tab.tab_id,action:'fill',locator:{selector:'#blocked'},text:'invisible field',timeout_ms:1800});
  await shown();check(true,'real browser input attempt displays frame/pointer via the native helper');
  assert.equal((await input).error?.code,'BROWSER_TIMEOUT');await hidden();check(true,'failed browser input releases the visible lifetime');
  await call('browser_read',{tab_id:tab.tab_id,operation:'text'});
  await call('browser_tabs',{operation:'reconcile',tab_id:tab.tab_id,recovery_note:'Hidden fixture input stayed unchanged.'});
  const waiting=desktop.request('browser_wait',{tab_id:tab.tab_id,condition:'visible',locator:{selector:'#blocked'},timeout_ms:900});
  await pause(100);await hidden();assert.equal((await waiting).data?.verification,'failed');check(true,'browser verification waits stay hidden');
  await call('browser_session',{operation:'end'});
  await call('desktop_act',{action:'focus_window',window_id});await call('desktop_act',{action:'focus',ref});await hidden();
  const cpu=desktop.request('desktop_run',{code:'while(true){}',timeout_ms:5000});await pause(200);await hidden();
  const stopped=Date.now();assert.ok((await inspect('escape')).sent);const reply=await cpu;
  check((reply.error??reply.data?.error)?.code==='USER_STOPPED'&&Date.now()-stopped<1500,'physical Escape stops CPU work even while visual effects are hidden');
  await call('desktop_system',{operation:'control_status'});await hidden();check(true,'Escape leaves both overlay windows hidden after helper reset');
  process.stdout.write(`Activity smoke passed ${checks} checks; independent window observations stayed in RAM.\n`);
} finally {desktop.close();lines.close();probe.kill();fixture.kill();await web.close();}
